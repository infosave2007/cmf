fn toy_encoder(seed: u64) -> (EncoderRecord, Vec<TensorSpec>) {
    let vocab = toy_vocab();
    let cfg = toy_config();
    let mut rng = Rng(seed);
    let tensors = cfg
        .tensor_layout(vocab.len())
        .into_iter()
        .map(|(name, dtype, shape)| {
            let data = if dtype == TensorDtype::U8 {
                vocab.clone()
            } else {
                rng.vec(shape.iter().product())
                    .iter()
                    .flat_map(|v| v.to_le_bytes())
                    .collect()
            };
            TensorSpec {
                name,
                dtype,
                shape,
                data,
            }
        })
        .collect();
    let record = EncoderRecord {
        kind: manifest::ENCODER_KIND.into(),
        source: EncoderSource {
            name: "toy encoder (format tests)".into(),
            onnx_sha256: sha(b"toy onnx"),
            tokenizer_json_sha256: sha(b"toy tokenizer.json"),
            vocab_sha256: sha(&vocab),
        },
        config: cfg,
        tokenizer: TokenizerRecord::bert_uncased(
            SpecialIds {
                pad: 0,
                unk: 1,
                cls: 2,
                sep: 3,
                mask: 4,
            },
            16,
            "toy tables",
        ),
        pooling: manifest::POOLING.into(),
        normalization: manifest::NORMALIZATION
            .iter()
            .map(|s| s.to_string())
            .collect(),
        dim: TOY_HIDDEN as u64,
        tensors_sha256: "0".repeat(64),
        golden_texts: manifest::DEFAULT_ENCODER_GOLDEN_TEXTS
            .iter()
            .map(|s| s.to_string())
            .collect(),
    };
    (record, tensors)
}

