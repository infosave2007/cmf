fn grid(n_odd: u64, theta_on: bool) -> Vec<GridEntry> {
    certify::THRESHOLDS
        .iter()
        .enumerate()
        .map(|(j, &t)| {
            let accepted = n_odd.saturating_sub(j as u64 / 4);
            GridEntry {
                t,
                accepted,
                correct: accepted.saturating_sub(u64::from(theta_on)),
                lb: if accepted == 0 {
                    0.0
                } else {
                    0.5 + j as f64 / 100.0
                },
                novelty_rejected: u64::from(theta_on && j > 3),
            }
        })
        .collect()
}

fn toy_gate(n_cal: u64, temperature: f32) -> Gate {
    let n_even = n_cal.div_ceil(2);
    let n_odd = n_cal / 2;
    Gate {
        temperature: temperature as f64,
        novelty_theta: 0.75f32 as f64,
        tau: 0.8f32 as f64,
        certified: true,
        rule: GateRule::standard(),
        evidence: Evidence {
            even: EvenEvidence {
                n: n_even,
                n_t: n_even,
                nll: 0.20523418281301234,
                log_t: (temperature as f64).ln(),
                nfev: 14,
                status: 0,
            },
            odd: OddEvidence {
                n: n_odd,
                accepted: n_odd,
                correct: n_odd.saturating_sub(1),
                grid: grid(n_odd, true),
                grid_theta_off: grid(n_odd, false),
            },
            calibration: CalibrationEvidence {
                n: n_cal,
                correct: n_cal - 1,
            },
        },
    }
}

fn random_row(
    rng: &mut Rng,
    task: u32,
    split: Split,
    flags: u8,
    source: Source,
    nnz: usize,
) -> Row {
    let mut idx: Vec<u16> = Vec::new();
    // nnz distinct ascending indices out of DIM_H.
    let mut chosen = vec![false; DIM_H];
    let mut left = nnz;
    while left > 0 {
        let i = rng.below(DIM_H);
        if !chosen[i] {
            chosen[i] = true;
            left -= 1;
        }
    }
    for (i, &c) in chosen.iter().enumerate() {
        if c {
            idx.push(i as u16);
        }
    }
    let val = (0..nnz).map(|_| rng.f() * 0.25 + 0.3).collect();
    Row {
        task,
        split,
        flags,
        source,
        weight: source.default_weight(),
        phi_p: rng.vec(TOY_HIDDEN),
        h_idx: idx,
        h_val: val,
    }
}

/// The skill tensors and rows kept for comparisons.
struct ToySkill {
    skill: NewSkill,
    rows: Rows,
    rows_learned: Option<Rows>,
}

/// `full`: every optional manifest field is used (cold-start task without a
/// topology, an inactive one-row task, learned rows in both places, the learned
/// record, a union training input, a carve-out, an unsorted rubric, `k_source`).
fn toy_skill(id: &str, labels: &[&str], k: u64, full: bool, seed: u64) -> ToySkill {
    let mut rng = Rng(seed);
    let n_data = labels.len();
    let mut tasks = Vec::new();
    let mut topologies = Vec::new();
    let mut n_train_rows = Vec::new();
    for (i, &label) in labels.iter().enumerate() {
        let one_row = full && i == n_data - 1;
        let n_train = if one_row { 1 } else { 4 };
        let k_i = k.min(n_train - 1);
        topologies.push(Some(Topology {
            mean: rng.vec(SIGNAL),
            basis: rng.vec(k_i as usize * SIGNAL),
        }));
        n_train_rows.push(n_train as usize);
        tasks.push(TaskRecord {
            i: i as u64,
            label: label.into(),
            state: if one_row {
                TaskState::Inactive
            } else {
                TaskState::Active
            },
            origin: TaskOrigin::Data,
            k: k_i,
            n_train,
            err_mean: 0.2 + i as f64 * 0.01,
            err_std: 0.05,
            mean_sha256: None,
            basis_sha256: None,
        });
    }
    let mut all_labels: Vec<String> = labels.iter().map(|s| s.to_string()).collect();
    if full {
        all_labels.push("zz_cold".into());
        tasks.push(TaskRecord {
            i: n_data as u64,
            label: "zz_cold".into(),
            state: TaskState::Quarantined,
            origin: TaskOrigin::ColdStart,
            k: 0,
            n_train: 0,
            err_mean: 0.0,
            err_std: 0.0,
            mean_sha256: None,
            basis_sha256: None,
        });
        topologies.push(None);
    }
    // Rows: train by task, calibration with both flags, learned (full only).
    let n_cal = 7usize;
    let mut w = RowsWriter::new(TOY_HIDDEN, DIM_H).unwrap();
    for (t, &n) in n_train_rows.iter().enumerate() {
        for _ in 0..n {
            let nnz = 5 + rng.below(40);
            w.push(&random_row(
                &mut rng,
                t as u32,
                Split::Train,
                0,
                Source::Data,
                nnz,
            ))
            .unwrap();
        }
    }
    for j in 0..n_cal {
        let mut flags = 0u8;
        if j % 2 == 1 {
            flags |= rows::FLAG_ODD_HALF;
        }
        if j % 5 == 4 {
            flags |= rows::FLAG_HOLDOUT;
        }
        let nnz = rng.below(30);
        w.push(&random_row(
            &mut rng,
            (j % n_data) as u32,
            Split::Calibration,
            flags,
            Source::Data,
            nnz,
        ))
        .unwrap();
    }
    if full {
        for (t, src) in [(0u32, Source::Oracle), (1, Source::ClientFeedback)] {
            w.push(&random_row(&mut rng, t, Split::Learned, 0, src, 12))
                .unwrap();
        }
    }
    let rows_blob = w.finish();
    let rows = Rows::decode(&rows_blob).unwrap();
    let rows_learned_blob = full.then(|| {
        let mut lw = RowsWriter::new(TOY_HIDDEN, DIM_H).unwrap();
        lw.push(&random_row(
            &mut rng,
            0,
            Split::Learned,
            0,
            Source::Oracle,
            9,
        ))
        .unwrap();
        lw.push(&random_row(
            &mut rng,
            2,
            Split::Learned,
            0,
            Source::Agreement,
            0,
        ))
        .unwrap();
        lw.finish()
    });
    let rows_learned = rows_learned_blob.as_ref().map(|b| Rows::decode(b).unwrap());
    let n_train: u64 = n_train_rows.iter().sum::<usize>() as u64;
    let mut criteria = serde_json::Map::new();
    let order: Vec<&str> = if full {
        labels.iter().rev().copied().collect()
    } else {
        labels.to_vec()
    };
    for l in order {
        criteria.insert(
            l.to_string(),
            json!(format!("The customer asks about {l}.")),
        );
    }
    let gate = toy_gate(n_cal as u64, TOY_T);
    let mut recipe = Recipe::standard(k);
    let data = if full {
        recipe.k_source = Some("max-recipe/cv.json chosen_K".into());
        DataRecord {
            train: TrainRecord {
                n: n_train,
                sha256: sha(b"train+dev"),
                parts: vec![
                    InputPart {
                        name: "train".into(),
                        n: n_train - 2,
                        sha256: sha(b"train"),
                    },
                    InputPart {
                        name: "dev".into(),
                        n: 2,
                        sha256: sha(b"dev"),
                    },
                ],
            },
            calibration: manifest::CalibrationRecord {
                n: n_cal as u64,
                sha256: sha(b"train+dev"),
                source: manifest::CALIBRATION_CARVE_OUT.into(),
            },
            dev: None,
            halves_rule: certify::HALVES_RULE.into(),
            holdout_rule: manifest::HOLDOUT_RULE.into(),
        }
    } else {
        DataRecord {
            train: TrainRecord {
                n: n_train,
                sha256: sha(b"train"),
                parts: vec![],
            },
            calibration: manifest::CalibrationRecord {
                n: n_cal as u64,
                sha256: sha(b"calibration"),
                source: manifest::CALIBRATION_FROM_FILE.into(),
            },
            dev: Some(DevRecord {
                n: 5,
                correct: 4,
                sha256: sha(b"dev"),
            }),
            halves_rule: certify::HALVES_RULE.into(),
            holdout_rule: manifest::HOLDOUT_RULE.into(),
        }
    };
    let manifest = SkillManifest {
        schema: manifest::SKILL_SCHEMA.into(),
        id: id.into(),
        taxonomy_version: if full { 2 } else { 1 },
        representation_id: String::new(),
        recipe,
        labels: all_labels,
        tasks,
        gate: gate.clone(),
        rubric: Some(Rubric::new("Pick the intent of the message.", criteria)),
        data,
        rows: RowsRecord::default(),
        rows_learned: None,
        learned: full.then(|| LearnedRecord {
            traffic_sha256: sha(b"traffic"),
            oracle_model: "deepseek/deepseek-v4.1-flash".into(),
            calls: 7,
            answers_reused: 3,
            promoted_labels: vec![labels[0].into()],
            rejected_labels: vec![labels[1].into()],
            gate_before: gate.clone(),
            gate_after: toy_gate(n_cal as u64, 0.031),
        }),
    };
    ToySkill {
        skill: NewSkill {
            manifest,
            topologies,
            rows: rows_blob,
            rows_learned: rows_learned_blob,
        },
        rows,
        rows_learned,
    }
}

