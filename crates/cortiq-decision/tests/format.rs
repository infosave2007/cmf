/// alpha's manifest with task `i` refitted (new topology values, same k).
fn refit(
    m: &SkillManifest,
    i: usize,
    seed: u64,
) -> (SkillManifest, BTreeMap<usize, Option<Topology>>) {
    let mut rng = Rng(seed);
    let mut m = m.clone();
    let k = m.tasks[i].k as usize;
    m.tasks[i].err_mean += 0.125;
    m.tasks[i].n_train += 25;
    let topo = Topology {
        mean: rng.vec(SIGNAL),
        basis: rng.vec(k * SIGNAL),
    };
    (m, BTreeMap::from([(i, Some(topo))]))
}

