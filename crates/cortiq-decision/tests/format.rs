fn read_all(path: &Path) -> (CmfHeader, Vec<TensorSpec>) {
    let m = CmfModel::open(path).unwrap();
    let specs = m
        .tensors
        .iter()
        .map(|e| TensorSpec {
            name: e.name.clone(),
            dtype: e.dtype,
            shape: e.shape.clone(),
            data: m.entry_bytes(e).to_vec(),
        })
        .collect();
    (m.header.clone(), specs)
}

/// Copy `src` to `dst` through the plain CMF writer, editing header and tensors.
fn rewrite(src: &Path, dst: &Path, f: impl FnOnce(&mut CmfHeader, &mut Vec<TensorSpec>)) {
    let (mut h, mut t) = read_all(src);
    f(&mut h, &mut t);
    CmfModel::write(dst, &h, &t, None, None).unwrap();
}

fn spec_mut<'a>(t: &'a mut [TensorSpec], name: &str) -> &'a mut TensorSpec {
    t.iter_mut()
        .find(|s| s.name == name)
        .unwrap_or_else(|| panic!("no tensor {name}"))
}

/// Edit the JSON of `decision.manifest` (canonical bytes written back); with
/// `fix_rid` the representation_id is recomputed.
fn edit_manifest(t: &mut [TensorSpec], fix_rid: bool, f: impl FnOnce(&mut Value)) {
    let s = spec_mut(t, manifest::MANIFEST_TENSOR);
    let mut v: Value = canonical::parse(&s.data).unwrap();
    f(&mut v);
    if fix_rid {
        let rid = manifest::representation_id(&v["representation"]);
        v["representation_id"] = json!(rid);
    }
    s.data = canonical::to_vec(&v);
    s.shape = vec![s.data.len()];
}

fn refused(path: &Path, verify: Verify) -> Refusal {
    DecisionModel::open(path, verify).expect_err("the file must be refused")
}

fn bits(v: &[f32]) -> Vec<u32> {
    v.iter().map(|x| x.to_bits()).collect()
}

