#[test]
fn rows_blob_round_trips_nnz_0_to_4096() {
    let (dp, dh) = (384usize, 4096usize);
    let mut rng = Rng(5);
    let mut rows = Rows::new(dp, dh).unwrap();
    let nnzs = [0usize, 1, 2, 3, 17, 100, 1000, 4095, 4096];
    for (j, &nnz) in nnzs.iter().enumerate() {
        let mut h = vec![0.0f32; dh];
        let mut left = nnz;
        while left > 0 {
            let i = rng.below(dh);
            if h[i] == 0.0 {
                h[i] = rng.f() + 2.0; // never 0
                left -= 1;
            }
        }
        let (split, flags, source) = match j % 3 {
            0 => (Split::Train, 0, Source::Data),
            1 => (
                Split::Calibration,
                rows::FLAG_ODD_HALF | rows::FLAG_HOLDOUT,
                Source::Data,
            ),
            _ => (Split::Learned, 0, Source::ClientFeedback),
        };
        rows.rows.push(Row::from_dense(
            j as u32,
            split,
            flags,
            source,
            1.5,
            rng.vec(dp),
            &h,
        ));
        assert_eq!(rows.rows.last().unwrap().nnz(), nnz);
        assert_eq!(bits(&rows.rows.last().unwrap().phi_h_dense(dh)), bits(&h));
    }
    rows.rows.sort_by_key(|r| r.split);
    let blob = rows.encode().unwrap();
    let expect_len: usize =
        rows::HEADER_LEN + rows.rows.iter().map(Row::encoded_len).sum::<usize>();
    assert_eq!(blob.len(), expect_len);
    assert_eq!(&blob[..4], b"CDRW");
    let back = Rows::decode(&blob).unwrap();
    assert_eq!(back, rows);
    let h = rows::read_header(&blob).unwrap();
    assert_eq!((h.n_rows, h.dim_p, h.dim_h), (nnzs.len(), dp, dh));
    // The incremental writer produces the same bytes.
    let mut w = RowsWriter::new(dp, dh).unwrap();
    for r in &rows.rows {
        w.push(r).unwrap();
    }
    assert_eq!(w.counts(), [3, 3, 3]);
    assert_eq!(w.finish(), blob);
    // The signal is [φ_P ; 0.5·φ_H].
    let r = &back.rows[3];
    let s = r.signal(dh);
    assert_eq!(bits(&s[..dp]), bits(&r.phi_p));
    for (&i, &v) in r.h_idx.iter().zip(&r.h_val) {
        assert_eq!(s[dp + i as usize].to_bits(), (0.5 * v).to_bits());
    }
}

#[test]
fn rows_blob_rejects_malformed_input() {
    let (dp, dh) = (4usize, 64usize);
    let row = |idx: Vec<u16>| Row {
        task: 0,
        split: Split::Train,
        flags: 0,
        source: Source::Data,
        weight: 1.0,
        phi_p: vec![0.5; dp],
        h_val: vec![0.25; idx.len()],
        h_idx: idx,
    };
    let good = {
        let mut r = Rows::new(dp, dh).unwrap();
        r.rows.push(row(vec![1, 5, 9]));
        r.encode().unwrap()
    };
    assert!(Rows::decode(&good).is_ok());
    // Offsets inside the only row.
    let idx_at = rows::HEADER_LEN + rows::ROW_FIXED_LEN + 4 * dp;
    let expect_err = |b: &[u8], what: &str| {
        let e = Rows::decode(b).expect_err(what).to_string();
        assert!(e.contains(what), "'{e}' does not mention '{what}'");
    };
    // Non-ascending and repeated indices.
    let mut b = good.clone();
    b[idx_at..idx_at + 2].copy_from_slice(&7u16.to_le_bytes()); // 7, 5, 9
    expect_err(&b, "strictly ascending");
    let mut b = good.clone();
    b[idx_at + 2..idx_at + 4].copy_from_slice(&1u16.to_le_bytes()); // 1, 1, 9
    expect_err(&b, "strictly ascending");
    let mut b = good.clone();
    b[idx_at + 4..idx_at + 6].copy_from_slice(&64u16.to_le_bytes()); // 1, 5, 64
    expect_err(&b, "out of range");
    // Writers refuse the same rows.
    let mut w = RowsWriter::new(dp, dh).unwrap();
    assert!(w.push(&row(vec![3, 2])).is_err());
    assert!(w.push(&row(vec![2, 2])).is_err());
    assert!(w.push(&row(vec![64])).is_err());
    // Header.
    let mut b = good.clone();
    b[0] = b'X';
    expect_err(&b, "magic");
    let mut b = good.clone();
    b[4] = 2;
    expect_err(&b, "version");
    let mut b = good.clone();
    b[20] = 1;
    expect_err(&b, "reserved header");
    let mut b = good.clone();
    b[16..20].copy_from_slice(&70000u32.to_le_bytes());
    expect_err(&b, "dim_h");
    // Row fields.
    let f = rows::HEADER_LEN;
    let mut b = good.clone();
    b[f + 4] = 3;
    expect_err(&b, "unknown split");
    let mut b = good.clone();
    b[f + 6] = 4;
    expect_err(&b, "unknown source");
    let mut b = good.clone();
    b[f + 7] = 1;
    expect_err(&b, "reserved row byte");
    let mut b = good.clone();
    b[f + 5] = rows::FLAG_ODD_HALF;
    expect_err(&b, "calibration rows only");
    let mut b = good.clone();
    b[f + 8..f + 12].copy_from_slice(&0.0f32.to_le_bytes());
    expect_err(&b, "weight");
    let mut b = good.clone();
    b[f + 12..f + 16].copy_from_slice(&65u32.to_le_bytes());
    expect_err(&b, "exceeds dim_h");
    let mut b = good.clone();
    b[f + 16..f + 20].copy_from_slice(&f32::NAN.to_le_bytes());
    expect_err(&b, "finite");
    // Length.
    expect_err(&good[..good.len() - 1], "truncated");
    let mut b = good.clone();
    b.push(0);
    expect_err(&b, "trailing");
    let mut b = good.clone();
    b[8..12].copy_from_slice(&2u32.to_le_bytes());
    expect_err(&b, "truncated");
    // Split order: a train row after a calibration row.
    let mut r = Rows::new(dp, dh).unwrap();
    let mut cal = row(vec![1]);
    cal.split = Split::Calibration;
    r.rows.push(cal);
    r.rows.push(row(vec![2]));
    assert!(r.encode().unwrap_err().to_string().contains("order"));
}

