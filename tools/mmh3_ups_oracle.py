# Pure-3D backbone (identical to training code)
# ==========================================
class LatentResizer3D(nn.Module):
    def __init__(self, in_channels=24, in_blocks=12, out_blocks=12,
                 channels=512, dropout=0.1, attn=False,
                 temporal_every=2, temporal_kernel=5):
        super().__init__()
        self.conv_in = nn.Conv3d(in_channels, channels, 3, padding=1)
        embed_dim = 64
        self.embed = nn.Sequential(
            nn.Linear(1, embed_dim), nn.SiLU(), nn.Linear(embed_dim, embed_dim))
        
        self.in_blocks = nn.ModuleList()
        for b in range(in_blocks):
            if (b == 1 or b == in_blocks - 1) and attn:
                self.in_blocks.append(AttnBlock3D(channels))
            self.in_blocks.append(ResBlockEmb3D(channels, embed_dim, dropout))
            if temporal_every > 0 and b % temporal_every == 0:
                self.in_blocks.append(TemporalConv(channels, temporal_kernel))
                
        self.out_blocks = nn.ModuleList()
        for b in range(out_blocks):
            if (b == 1 or b == out_blocks - 1) and attn:
                self.out_blocks.append(AttnBlock3D(channels))
            self.out_blocks.append(ResBlockEmb3D(channels, embed_dim, dropout))
            if temporal_every > 0 and b % temporal_every == 0:
                self.out_blocks.append(TemporalConv(channels, temporal_kernel))
                
        self.norm_out = normalization(channels)
        self.conv_out = nn.Conv3d(channels, in_channels, 3, padding=1)

    def forward(self, x, scale=None, target_size=None):
        if target_size is not None:
            size = target_size
        elif scale is not None:
            size = tuple(int(round(s * scale)) for s in x.shape[-3:])
        else:
            return x

        if size == x.shape[-3:]:
            return x

        scale_emb = torch.tensor(
            [scale - 1 if scale is not None else 0.0],
            dtype=x.dtype, device=x.device).unsqueeze(0)
        emb = self.embed(scale_emb)

        x = self.conv_in(x)
        for b in self.in_blocks:
            if isinstance(b, ResBlockEmb3D):
                emb_t = emb.expand(x.shape[0], -1)
                x = b(x, emb_t)
            else:
                x = b(x)

        x = F.interpolate(x, size=size, mode="trilinear", align_corners=False)

        for b in self.out_blocks:
            if isinstance(b, ResBlockEmb3D):
                emb_t = emb.expand(x.shape[0], -1)
                x = b(x, emb_t)
            else:
                x = b(x)

        x = self.norm_out(x)
        x = F.silu(x)
        x = self.conv_out(x)
        return x



def save_st(path, tensors):
    hdr, blob = {}, bytearray()
    for k, v in tensors.items():
        v = v.contiguous().to(torch.float32).cpu()
        b = v.numpy().tobytes()
        hdr[k] = {"dtype": "F32", "shape": list(v.shape), "data_offsets": [len(blob), len(blob)+len(b)]}
        blob += b
    h = json.dumps(hdr).encode()
    with open(path, "wb") as f:
        f.write(struct.pack("<Q", len(h))); f.write(h); f.write(blob)

if __name__ == "__main__":
    weights, out_path = sys.argv[1], sys.argv[2]
    sd = load_file(weights)
    sd = {k: v.to(torch.float32) for k, v in sd.items()}
    # architecture is fixed by the checkpoint: 24 channels in, 512 wide
    model = LatentResizer3D(in_channels=24, in_blocks=12, out_blocks=12,
                            channels=512, dropout=0.0, attn=False,
                            temporal_every=2, temporal_kernel=5)
    missing, unexpected = model.load_state_dict(sd, strict=False)
    print("missing:", len(missing), "unexpected:", len(unexpected))
    if missing: print("  e.g.", missing[:4])
    if unexpected: print("  e.g.", unexpected[:4])
    model.eval()
    torch.manual_seed(7)
    # a small volume: 24 channels, 3 frames, 6x8 -> 12x16
    x = torch.randn(1, 24, 3, 6, 8, dtype=torch.float32)
    with torch.inference_mode():
        y = model(x, scale=2.0, target_size=(3, 12, 16))
    print("in", tuple(x.shape), "out", tuple(y.shape), "rms", float(y.pow(2).mean().sqrt()))
    save_st(out_path, {"x": x[0], "y": y[0]})
    print("wrote", out_path)
